import Foundation

public enum LocaleExporter {
    public static func render(_ project: LocaleProject, catalog: LocaleCatalog) throws -> String {
        try project.validate()
        var output = ["escape_char /", "comment_char %", "", "% Generated by Linux Locale Editor. UTF-8.", "% Name: \(project.name)"]
        for category in LocaleCategory.allCases {
            let selection = try project.selection(category)
            // Validate the selected section without interpreting collation/ctype internals.
            let resolved = try catalog.resolve(selection.source, category: category)
            output += ["", category.rawValue]
            if selection.overrides.isEmpty {
                output.append("copy " + SourceSyntax.quote(selection.source))
            } else {
                if category == .time { try checkFormatRecursion(resolved, overrides: selection.overrides) }
                var emitted: Set<String> = []
                for entry in resolved.entries {
                    if let value = selection.overrides[entry.keyword] {
                        guard emitted.insert(entry.keyword).inserted else { continue }
                        output.append(entry.keyword + " " + value.source)
                    } else {
                        output.append(SourceSyntax.canonicalize(entry.text, escape: resolved.escape))
                    }
                }
                for key in selection.overrides.keys.sorted() where !emitted.contains(key) {
                    output.append(key + " " + selection.overrides[key]!.source)
                }
            }
            output.append("END " + category.rawValue)
        }
        return output.joined(separator: "\n") + "\n"
    }

    private static func checkFormatRecursion(_ section: SourceSection, overrides: [String: FieldValue]) throws {
        let targets: [Character: String] = ["x": "d_fmt", "X": "t_fmt", "c": "d_t_fmt", "r": "t_fmt_ampm"]
        var edges: [String: [String]] = [:]
        for key in targets.values {
            let value: String
            if case .text(let s) = overrides[key] { value = s }
            else if let entry = section.entry(key) { value = try SourceSyntax.unquote(entry.value, escape: section.escape) }
            else { continue }
            edges[key] = try FieldDefinition.formatConversions(value).compactMap { targets[$0] }
        }
        func visit(_ key: String, _ path: Set<String>) throws {
            guard !path.contains(key) else { throw LocaleEditorError("Recursive date/time format involving \(key). Use explicit components such as %Y-%m-%d.") }
            for next in edges[key] ?? [] { try visit(next, path.union([key])) }
        }
        for key in edges.keys { try visit(key, []) }
    }
}
